// Writes server/src/htxPages.ts (the MIS page list for People & teams on portal.heatronics.in) from the menu,
// client/src/nav/config.ts. Run: node --experimental-strip-types scripts/gen-htx-pages.mjs  (test: server/test/htxPages.test.ts)
import { writeFileSync } from 'node:fs';
import { NAV } from '../client/src/nav/config.ts';

export function catalogFromNav(nav) {
  const pages = nav.flatMap((s) => s.pages.map((p) => ({
    id: p.id, name: p.label, group: s.label,
    paths: [...new Set([p.href, ...(p.also ?? [])])],
    ...(p.exact ? { exact: true } : {}),
  })));
  return { portal: 'mis', pages };
}

if (process.argv[1]?.endsWith('gen-htx-pages.mjs')) {
  const body = `// GENERATED by scripts/gen-htx-pages.mjs from client/src/nav/config.ts. Do not edit by hand.\n// The MIS pages for People & teams on portal.heatronics.in/admin (server/src/htxGate.ts gates them).\nimport type { HtxCatalog } from './htxGate.js';\n\nexport const HTX_PAGES: HtxCatalog = ${JSON.stringify(catalogFromNav(NAV), null, 2)};\n`;
  writeFileSync('server/src/htxPages.ts', body);
  console.log('wrote server/src/htxPages.ts');
}
