// Writes server/src/planning/basePlanMonths.ts: the Base plan's months (revenue, GM, CM3, EBITDA, units, run-rate ARR)
// for GET /api/planning/vs-actual, because the server cannot import the client engine (rootDir src/).
// server/test/planVsActual.test.ts fails when this file is out of date. Re-run after the plan changes:
//   node --import tsx scripts/export-base-plan-months.ts
import fs from 'node:fs';
import { runPlan } from '../client/src/data/planning/engine.ts';
import { basePlan } from '../client/src/data/planning/basePlan.ts';
import { runRateArr } from '../client/src/data/planning/growth.ts';
import { planMonthsOf } from '../client/src/data/planning/planVsActual.ts';

const p = basePlan();
const r = runPlan(p);
const rows = planMonthsOf(r, p.startMonth, (e) => runRateArr(r, e));
const out = `// GENERATED by scripts/export-base-plan-months.ts — do not edit by hand.\nimport type { PlanMonthRow } from './planVsActual.js';\n\nexport const BASE_PLAN_START = ${JSON.stringify(p.startMonth)};\nexport const BASE_PLAN_MONTHS: PlanMonthRow[] = ${JSON.stringify(rows, null, 1)};\n`;
fs.writeFileSync(new URL('../server/src/planning/basePlanMonths.ts', import.meta.url), out);
console.log('wrote', rows.length, 'months');
