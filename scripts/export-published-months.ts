// Writes server/src/connectors/tally/publishedMonths.ts: the published MIS months before the Tally books start (1 Apr 2026),
// on the live basis and tied to the audited accounts (client PUBLISHED_MONTHS), so the server's "vs last year" figures have
// something to compare with: FY25-26 is not in this Tally company. The server cannot import the client (rootDir src/).
// server/test/publishedMonths.test.ts fails when this file is out of date. Re-run after the published history changes:
//   node --import tsx scripts/export-published-months.ts
import fs from 'node:fs';
import { PUBLISHED_MONTHS } from '../client/src/data/misDeck/publishedBasis.ts';

export const TALLY_BOOKS_START = '2026-04';
const r0 = (n: number) => Math.round(n);
export function publishedRows() {
  return PUBLISHED_MONTHS.filter((m) => m.key < TALLY_BOOKS_START).map((m) => ({
    period: m.key, netRevenue: r0(m.netRevenue), cogm: r0(m.cogm), grossMargin: r0(m.grossMargin), ebitda: r0(m.ebitda), netIncome: r0(m.netIncome),
  }));
}

if (process.argv[1]?.endsWith('export-published-months.ts')) {
  const rows = publishedRows();
  const out = `// GENERATED by scripts/export-published-months.ts — do not edit by hand.\n// Published MIS months (live basis, tied to the audited accounts) before the Tally books start.\n\nexport interface PublishedMonth { period: string; netRevenue: number; cogm: number; grossMargin: number; ebitda: number; netIncome: number }\nexport const TALLY_BOOKS_START = ${JSON.stringify(TALLY_BOOKS_START)};\nexport const PUBLISHED_MONTHS: PublishedMonth[] = ${JSON.stringify(rows, null, 1)};\n`;
  fs.writeFileSync(new URL('../server/src/connectors/tally/publishedMonths.ts', import.meta.url), out);
  console.log('wrote', rows.length, 'months');
}
