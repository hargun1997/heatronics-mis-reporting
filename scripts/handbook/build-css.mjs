// Generates client/src/pages/handbook/handbook.generated.css from the <style>
// block of the single-source handbook (client/src/content/handbook/handbook.html).
//
// The handbook HTML is also published standalone (the Claude artifact), so it
// ships its own stylesheet. Inside the app we reuse that stylesheet, scoped
// under `.hb`, minus the standalone page chrome (sidebar, top bar, dark mode)
// which the React layout provides natively. Run after editing handbook.html:
//   node scripts/handbook/build-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const html = readFileSync(resolve(root, 'client/src/content/handbook/handbook.html'), 'utf8');
const css = (html.match(/<style>([\s\S]*?)<\/style>/) || [])[1];
if (!css) throw new Error('No <style> block found in handbook.html');

// Standalone-page chrome that the app replaces with React components.
const DROP = [/^html\b/, /^body\b/, /^\*/, /^:root/, /^\.tabs\b/, /^\.wrap\b/, /^\.side\b/, /^\.navtree\b/,
  /^\.part\b/, /^\.ch(?![\w-])/, /^\.sub\b/, /^\.hide\b/, /^\.bar\b/, /^\.crumb\b/, /^\.scrim\b/,
  /^\.chnav\b/, /^\.toc2\b/, /^\.car\b/];
const DROP_MEDIA = [/prefers-color-scheme/, /min-width:\s*1100px/, /prefers-reduced-motion/];

function splitTop(str, sep) {
  const out = []; let depth = 0, cur = '';
  for (const ch of str) {
    if (ch === '(') depth++; else if (ch === ')') depth--;
    if (ch === sep && depth === 0) { out.push(cur); cur = ''; } else cur += ch;
  }
  out.push(cur); return out;
}

function process(block) {
  let out = '', i = 0;
  const s = block.replace(/\/\*[\s\S]*?\*\//g, '');
  while (i < s.length) {
    const open = s.indexOf('{', i);
    if (open < 0) break;
    const head = s.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < s.length && depth) { if (s[j] === '{') depth++; else if (s[j] === '}') depth--; j++; }
    const body = s.slice(open + 1, j - 1);
    i = j;
    if (head.startsWith('@media')) {
      if (DROP_MEDIA.some((r) => r.test(head))) continue;
      const inner = process(body);
      if (inner.trim()) out += `${head}{\n${inner}}\n`;
      continue;
    }
    if (head.startsWith('@')) continue;
    const sels = splitTop(head, ',').map((x) => x.trim()).filter((x) => x && !DROP.some((r) => r.test(x)));
    if (!sels.length) continue;
    out += `${sels.map((x) => `.hb ${x}`).join(',')}{${body.trim()}}\n`;
  }
  return out;
}

const header = `/* GENERATED by scripts/handbook/build-css.mjs from handbook.html — do not edit by hand. */
.hb{
  --bg:#f8fafc; --paper:#ffffff; --sunk:#f1f5f9; --ink:#0f172a; --muted:#64748b; --line:#e2e8f0;
  --accent:#ba2f06; --accent-soft:#fff3ed; --accent-ink:#93270c;
  --dr:#1d4ed8; --dr-soft:#e0ecfb; --cr:#b45309; --cr-soft:#fdf0e1;
  --ok:#047857; --ok-soft:#e3f5ec; --warn:#92400e; --warn-soft:#fef3c7; --bad:#b91c1c; --bad-soft:#fde8e8;
  --f-body:inherit; --f-head:'Archivo Expanded','Archivo',ui-sans-serif,system-ui,sans-serif;
  --f-mono:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace;
  color:var(--ink); font-size:15.5px; line-height:1.6;
}
.hb .chapter,.hb .partband,.hb .cover,.hb [id],.hb .chapter h3{scroll-margin-top:130px!important}
.hb .chno{justify-self:start;align-self:start}
/* In the app the page header carries the title; the cover keeps its guidance callouts. */
.hb.hb-cover>.eyebrow,.hb.hb-cover>h1,.hb.hb-cover>.lede{display:none}
.hb.hb-cover{display:flex;flex-direction:column;gap:12px}
.hb h1,.hb h2{font-weight:800;letter-spacing:-0.01em}
`;
writeFileSync(resolve(root, 'client/src/pages/handbook/handbook.generated.css'), header + process(css));
console.log('handbook.generated.css written');
